def Jaccard(s1, s2):
    # Implement
    union = s1 | s2

    if not union:
        return 0.0

    return len(s1 & s2) / len(union)

def mostSimilar(i, N, usersPerItem):
    # Implement...
    similarities = []
    queryUsers = usersPerItem[i]

    for j in usersPerItem:
        if j == i:
            continue

        similarity = Jaccard(queryUsers, usersPerItem[j])
        similarities.append((similarity, j))


    similarities.sort(reverse=True)

    return similarities[:N]



