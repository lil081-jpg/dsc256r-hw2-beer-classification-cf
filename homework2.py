def pipeline(reg, catID, dataTrain, dataValid, dataTest,
             includeCat=True, includeReview=True, includeLength=True):

    mod = linear_model.LogisticRegression(
        C=reg,
        class_weight='balanced',
        max_iter=1000
    )

    maxLength = max(len(d['review/text']) for d in dataTrain)

    Xtrain = [
        feat(d, catID, maxLength, includeCat, includeReview, includeLength)
        for d in dataTrain
    ]
    Xvalid = [
        feat(d, catID, maxLength, includeCat, includeReview, includeLength)
        for d in dataValid
    ]
    Xtest = [
        feat(d, catID, maxLength, includeCat, includeReview, includeLength)
        for d in dataTest
    ]

    yTrain = [d['beer/ABV'] > 7 for d in dataTrain]
    yValid = [d['beer/ABV'] > 7 for d in dataValid]
    yTest = [d['beer/ABV'] > 7 for d in dataTest]

    mod.fit(Xtrain, yTrain)

    def BER(yTrue, yPred):
        yTrue = numpy.asarray(yTrue, dtype=bool)
        yPred = numpy.asarray(yPred, dtype=bool)

        falsePositiveRate = numpy.mean(yPred[~yTrue])
        falseNegativeRate = numpy.mean(~yPred[yTrue])

        return (falsePositiveRate + falseNegativeRate) / 2

    vBER = BER(yValid, mod.predict(Xvalid))
    tBER = BER(yTest, mod.predict(Xtest))

    return mod, vBER, tBER

