def predictRatingQ7(user,item,ratingMean,reviewsPerUser,usersPerItem,itemsPerUser,userAverages,itemAverages):
    # Your solution here
    prediction = ratingMean

    # Adjust for the user's usual rating.
    if user in userAverages:
        n = len(itemsPerUser[user])
        prediction += (n / (n + 5)) * (
            userAverages[user] - ratingMean
        )

    # Adjust for the item's usual rating.
    if item in itemAverages:
        n = len(usersPerItem[item])
        prediction += (n / (n + 10)) * (
            itemAverages[item] - ratingMean
        )

    return max(1.0, min(5.0, prediction))
