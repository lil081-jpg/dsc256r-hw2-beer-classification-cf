def feat(d, catID, maxLength, includeCat = True, includeReview = True, includeLength = True):
    features = []
    if includeCat:
        # My implementation is modular such that this one function concatenates all three features together,
        # depending on which are selected
        categoryFeatures = [0] * len(catID)
        style = d['beer/style']

        if style in catID:
            categoryFeatures[catID[style]] = 1

        features.extend(categoryFeatures)

    if includeReview:
        ratingKeys = [
            'review/aroma',
            'review/appearance',
            'review/palate',
            'review/taste',
            'review/overall'
        ]
        features.extend(d[key] for key in ratingKeys)

    if includeLength:
        normalizedLength = (
            len(d['review/text']) / maxLength if maxLength > 0 else 0
        )
        features.append(normalizedLength)

    return features + [1]

